// Vertaalfunctie
window.t = function(key, taal) {
  var entry = window.vertalingen[key];
  if (!entry) return key;
  return entry[taal] || entry.nl || key;
};

// Dag vertalen
window.vertaalDag = function(dag, taal) {
  var dagMap = {
    'Maandag': 'maandag', 'Dinsdag': 'dinsdag', 'Woensdag': 'woensdag',
    'Donderdag': 'donderdag', 'Vrijdag': 'vrijdag', 'Zaterdag': 'zaterdag', 'Zondag': 'zondag'
  };
  var key = dagMap[dag];
  return key ? window.t(key, taal) : dag;
};

